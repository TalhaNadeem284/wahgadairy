"use strict";
// Builds mobile/www from the desktop app's own files, so the phone app always
// has the same screens (../renderer) and the same data logic (../db.js).
//   node build-www.js
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(__dirname, "www");
const SRC = path.join(__dirname, "src");
const read = (p) => fs.readFileSync(p, "utf8");
const write = (name, text) => fs.writeFileSync(path.join(OUT, name), text);
const copy = (from, name) => fs.copyFileSync(from, path.join(OUT, name || path.basename(from)));

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, "seed"), { recursive: true });

const version = JSON.parse(read(path.join(ROOT, "package.json"))).version;

// 1. screens + styles from the desktop renderer
copy(path.join(ROOT, "renderer", "app.js"));
copy(path.join(ROOT, "renderer", "styles.css"));

// 2. sql.js browser build + html2pdf
copy(path.join(ROOT, "node_modules", "sql.js", "dist", "sql-wasm.js"));
copy(path.join(ROOT, "node_modules", "sql.js", "dist", "sql-wasm.wasm"));
copy(path.join(__dirname, "node_modules", "html2pdf.js", "dist", "html2pdf.bundle.min.js"));

// 3. db.js and preload.js wrapped as browser scripts (require → phone shims)
const wrap = (code, exportAs, requireExpr) => `/* generated by build-www.js — do not edit */
(function () {
  const module = { exports: {} };
  const exports = module.exports;
  const __dirname = "/app";
  const require = ${requireExpr};
${code}
  ${exportAs ? `window.${exportAs} = module.exports;` : ""}
})();
`;
write("db-bundle.js", wrap(read(path.join(ROOT, "db.js")), "WAHGA_DB",
  `(n) => { const m = window.MOBILE_SHIMS[n]; if (!m) throw new Error("no phone shim for " + n); return m; }`));
write("preload-bundle.js", wrap(read(path.join(ROOT, "preload.js")), null,
  `(n) => { if (n !== "electron") throw new Error("preload needs " + n); return window.MOBILE_ELECTRON; }`));

// 4. the plain data handlers, copied from main.js (one-liners that just call db.*)
const handlerLines = read(path.join(ROOT, "main.js")).split(/\r?\n/)
  .filter((l) => /^handle\("[\w:]+",.*requireDb\(\); return db\.\w+\(.*\); \}\);\s*$/.test(l));
write("mobile-handlers.js", `/* generated by build-www.js from main.js — do not edit */
(function () {
  // online mode: every call goes to the server (window.WAHGA_ONLINE_DB), else the phone copy
  const db = new Proxy({}, { get: (_t, p) => (window.WAHGA_ONLINE_DB || window.WAHGA_DB)[p] });
  const requireDb = () => { if (!db.isOpen()) throw new Error("No database is open."); };
  const handle = (channel, fn) => { if (!window.MOBILE_HANDLERS[channel]) window.MOBILE_HANDLERS[channel] = fn; };
${handlerLines.join("\n")}
})();
`);

// 5. phone-only files
for (const f of ["shims.js", "drive-sync.js", "mobile-api.js", "mobile-ui.js", "mobile.css"]) copy(path.join(SRC, f));
write("version.js", `window.WAHGA_VERSION = ${JSON.stringify(version + " (Android)")};\n`);

// 6. no data ships with the phone app: it shows nothing until it is linked to
//    the shared wahga-dairy.db in Google Drive (and the APK carries no business data)

// 7. index.html: the desktop page + phone top bar + scripts in the right order
let html = read(path.join(ROOT, "renderer", "index.html"));
html = html.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/,
  `<meta http-equiv="Content-Security-Policy" content="default-src 'self' data: blob:; script-src 'self' 'wasm-unsafe-eval'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self' data: blob: https:;" />
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />`);
html = html.replace(`<link rel="stylesheet" href="styles.css" />`,
  `<link rel="stylesheet" href="styles.css" />\n  <link rel="stylesheet" href="mobile.css" />`);
html = html.replace(`<div id="app">`,
  `<header id="mobilebar"><button id="menuBtn" aria-label="Menu">☰</button><span class="title">Wahga Dairy Farm</span><button id="refreshBtn" aria-label="Refresh">🔄</button></header>\n  <div id="navshade"></div>\n  <div id="app">`);
html = html.replace(`<script src="app.js"></script>`, [
  "version.js", "sql-wasm.js", "shims.js", "db-bundle.js", "drive-sync.js", "mobile-api.js", "mobile-handlers.js",
  "preload-bundle.js", "html2pdf.bundle.min.js", "app.js", "mobile-ui.js",
].map((s) => `<script src="${s}"></script>`).join("\n  "));
write("index.html", html);

console.log(`www built: v${version}, ${handlerLines.length} data handlers from main.js`);
